/* WiFi test — SwarmBot Fase 7

   Conecta el ESP32-S3 a la red configurada (ver Kconfig / sdkconfig.defaults),
   imprime la IP obtenida y se reconecta automaticamente e indefinidamente
   ante cualquier desconexion (a diferencia del ejemplo oficial de ESP-IDF,
   que se rinde tras CONFIG_ESP_MAXIMUM_RETRY intentos: un robot del swarm
   debe seguir intentando mientras el router/hotspot exista).

   Basado en el ejemplo oficial ESP-IDF wifi/getting_started/station.
*/
